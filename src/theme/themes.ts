export function getTheme(name: ThemeName, resolvedMode: 'light' | 'dark'): Theme {
  const t = themes[name] || themes.playgrounditor;
  const colors = t[resolvedMode] || t.light;
  return {
    name,
    mode: resolvedMode,
    displayName: t.displayName,
    colors,
  };
}
